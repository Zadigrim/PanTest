// Generates components/ui/iconRegistry.ts from the assets/icons/ source SVGs.
//
// react-native-svg-transformer is intentionally NOT installed (frozen
// lockfile), so .svg files can't be imported as components. Like the
// inline strings in components/ui/Illustrations.tsx, the icon XML must be
// available as runtime string constants — this script produces that map
// (slug -> xml) from the source files, keyed by _index.json so the slugs
// stay in lockstep with the manifest.
//
// Re-run after adding/editing icons:  node scripts/gen-icon-registry.mjs
import { readFileSync, writeFileSync, existsSync, readdirSync } from 'fs'
import { join, dirname } from 'path'
import { fileURLToPath } from 'url'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const iconsDir = join(root, 'assets', 'icons')
const outFile = join(root, 'components', 'ui', 'iconRegistry.ts')

const index = JSON.parse(readFileSync(join(iconsDir, '_index.json'), 'utf8'))

const registry = {}
const missingFile = []        // manifest slug with no .svg
const noCurrentColor = []     // svg that won't recolor (no currentColor)

for (const entry of index) {
  const slug = entry.slug
  const file = join(iconsDir, `${slug}.svg`)
  if (!existsSync(file)) { missingFile.push(slug); continue }
  // Collapse inter-tag whitespace/newlines to a single line; the XML is
  // otherwise verbatim so it scales-to-fit via its own viewBox.
  const xml = readFileSync(file, 'utf8').replace(/\s*\n\s*/g, ' ').trim()
  registry[slug] = xml
  if (!xml.includes('currentColor')) noCurrentColor.push(slug)
}

// Source .svg files that aren't in the manifest (orphans).
const orphans = readdirSync(iconsDir)
  .filter((f) => f.endsWith('.svg'))
  .map((f) => f.replace(/\.svg$/, ''))
  .filter((slug) => !(slug in registry) && !missingFile.includes(slug))

const banner =
  '// AUTO-GENERATED by scripts/gen-icon-registry.mjs — do not edit by hand.\n' +
  '// Inline SVG strings for the assets/icons/ brand icon library. No\n' +
  '// react-native-svg-transformer (frozen lockfile), so the XML lives here as\n' +
  '// runtime strings, rendered via <SvgXml> with a currentColor re-ink (see\n' +
  '// components/ui/Icon.tsx). Re-run: node scripts/gen-icon-registry.mjs\n\n'

const body =
  `export const ICON_REGISTRY = ${JSON.stringify(registry, null, 2)} satisfies Record<string, string>\n\n` +
  'export type IconName = keyof typeof ICON_REGISTRY\n'

writeFileSync(outFile, banner + body)

console.log(`icon registry: wrote ${Object.keys(registry).length} icons -> ${outFile}`)
if (missingFile.length) console.warn(`  manifest slugs with NO .svg file: ${missingFile.join(', ')}`)
if (orphans.length) console.warn(`  .svg files NOT in _index.json: ${orphans.join(', ')}`)
if (noCurrentColor.length) console.warn(`  icons without currentColor (won't recolor): ${noCurrentColor.join(', ')}`)
